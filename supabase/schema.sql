-- Child tables of provider_profiles: public sees them only when
-- the parent is approved, owners always see their own.
-- provider_images is handled separately below because it carries a
-- second gate (moderation_status) that must apply to every reader.
do $$
declare t text;
begin
  foreach t in array array['provider_services','service_areas']
  loop
    execute format('drop policy if exists %1$I_public_read on public.%1$I', t);
    execute format($f$
      create policy %1$I_public_read on public.%1$I
        for select to anon, authenticated
        using (exists (
          select 1 from public.provider_profiles pp
          where pp.id = %1$I.provider_profile_id and pp.status = 'approved'
        ))
    $f$, t);

    execute format('drop policy if exists %1$I_owner_read on public.%1$I', t);
    execute format($f$
      create policy %1$I_owner_read on public.%1$I
        for select to authenticated
        using (exists (
          select 1 from public.provider_profiles pp
          where pp.id = %1$I.provider_profile_id and pp.user_id = auth.uid()
        ))
    $f$, t);

    execute format('drop policy if exists %1$I_owner_write on public.%1$I', t);
    execute format($f$
      create policy %1$I_owner_write on public.%1$I
        for insert to authenticated
        with check (exists (
          select 1 from public.provider_profiles pp
          where pp.id = %1$I.provider_profile_id and pp.user_id = auth.uid()
