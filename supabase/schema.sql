-- 6. Rating aggregates. Reviews are the only source of truth; these
--    two columns exist so a provider card can show ★4.8 (23) and so
--    search can order by rating without an N+1 query per card.
alter table public.provider_profiles
  add column if not exists rating_avg   numeric(3,2),
  add column if not exists review_count integer not null default 0,
  add column if not exists search_text  text not null default '';

create index if not exists provider_profiles_rating_idx
  on public.provider_profiles (rating_avg desc, review_count desc);

create or replace function public.refresh_provider_rating(p_profile_id uuid)
returns void
language sql
security definer
set search_path = public
as $$
  -- Aggregate functions cannot appear directly in an UPDATE's SET list,
  -- so the stats are computed in a CTE. It always yields exactly one
  -- row, which is what clears a provider whose last visible review was
  -- hidden or deleted instead of leaving a stale average behind.
  with stats as (
    select count(*)::int as n, round(avg(r.rating)::numeric, 2) as avg_rating
      from public.reviews r
     where r.provider_profile_id = p_profile_id
       and r.hidden = false
  )
  update public.provider_profiles pp
     set rating_avg   = stats.avg_rating,
         review_count = stats.n
    from stats
   where pp.id = p_profile_id;
$$;

create or replace function public.on_review_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare v_profile uuid;
begin
  -- TG_OP rather than coalesce(new.x, old.x): reading a field of the
  -- record that does not exist for this event errors in plpgsql.
  v_profile := case when tg_op = 'DELETE' then old.provider_profile_id
                    else new.provider_profile_id end;
  perform public.refresh_provider_rating(v_profile);
  return null;
end;
$$;

drop trigger if exists on_review_change on public.reviews;
create trigger on_review_change
  after insert or update or delete on public.reviews
  for each row execute function public.on_review_change();

-- 7. Searchable text. PostgREST cannot mix an embedded column with a
--    top-level one inside a single or=(...) filter, so "solar" could
--    never match a service name while also matching the business name.
--    Flattening the searchable fields into one column keeps search to
--    a single indexable predicate and covers areas too, so typing
--    "Chitungwiza" finds providers who serve it.
create or replace function public.build_provider_search(p_profile_id uuid)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(concat_ws(' ',
    pp.business_name,
    pp.slug,
    pp.description,
    pp.primary_category,
    pp.availability_note,
    (select string_agg(s.service_name, ' ')      from public.provider_services s where s.provider_profile_id = pp.id),
    (select string_agg(s.category, ' ')          from public.provider_services s where s.provider_profile_id = pp.id),
    (select string_agg(a.area_name, ' ')         from public.service_areas a     where a.provider_profile_id = pp.id)
  ), '')
  from public.provider_profiles pp
  where pp.id = p_profile_id;
$$;

-- Recomputed on every write to the parent. Mutating NEW rather than
-- issuing an UPDATE is what keeps this from re-firing itself.
create or replace function public.set_provider_search_text()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.search_text := coalesce(public.build_provider_search(new.id), '');
  return new;
end;
$$;

drop trigger if exists set_provider_search_text on public.provider_profiles;
create trigger set_provider_search_text
  before insert or update on public.provider_profiles
  for each row execute function public.set_provider_search_text();

-- A service or area changing does not touch the parent row, so the
-- denormalised copy is refreshed from the child side.
create or replace function public.touch_provider_search_text()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare v_profile uuid;
begin
  v_profile := case when tg_op = 'DELETE' then old.provider_profile_id
                    else new.provider_profile_id end;
  update public.provider_profiles
     set search_text = coalesce(public.build_provider_search(v_profile), '')
   where id = v_profile;
  return null;
end;
$$;

do $$
declare t text;
begin
  foreach t in array array['provider_services','service_areas']
  loop
    execute format('drop trigger if exists touch_provider_search_text on public.%I', t);
    execute format('create trigger touch_provider_search_text after insert or update or delete on public.%I for each row execute function public.touch_provider_search_text()', t);
  end loop;
end $$;

