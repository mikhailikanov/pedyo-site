$$;

drop trigger if exists on_auth_user_email_updated on auth.users;
create trigger on_auth_user_email_updated
  after update of email on auth.users
  for each row execute function public.handle_user_email_updated();

-- 3. Bump conversations.updated_at on new message.
--    The client also writes it explicitly; a trigger keeps order
--    correct when that second request fails.
create or replace function public.touch_conversation()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.conversations set updated_at = new.created_at where id = new.conversation_id;
  return new;
end;
$$;

drop trigger if exists on_message_insert_touch on public.messages;
create trigger on_message_insert_touch
  after insert on public.messages
  for each row execute function public.touch_conversation();

-- 4. Fan out notifications. Without this the unread badge is
--    permanently zero and the whole notification feature is inert.
create or replace function public.notify_conversation_members()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.notifications (user_id, title, body, type, data)
  select
    m.user_id,
    'New message',
    left(new.content, 120),
    'message',
    jsonb_build_object('conversation_id', new.conversation_id, 'sender_id', new.sender_id)
  from public.conversation_members m
  where m.conversation_id = new.conversation_id
    and m.user_id <> new.sender_id;

  update public.conversation_members
     set unread_count = unread_count + 1
   where conversation_id = new.conversation_id
     and user_id <> new.sender_id;

  return new;
end;
$$;

drop trigger if exists on_message_insert_notify on public.messages;
create trigger on_message_insert_notify
  after insert on public.messages
  for each row execute function public.notify_conversation_members();

-- Opening a thread clears only the viewer's counter and the viewer's
-- own message notifications.
create or replace function public.mark_thread_read(p_conversation_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.conversation_members
     set unread_count = 0
   where conversation_id = p_conversation_id
     and user_id = auth.uid();

  update public.notifications
     set read = true
   where user_id = auth.uid()
     and type = 'message'
     and data->>'conversation_id' = p_conversation_id::text;
end;
$$;

grant execute on function public.mark_thread_read(uuid) to authenticated;

