-- ------------------------------------------------------------
-- Helper functions (SECURITY DEFINER)
--
-- These exist to break RLS recursion. The conversations policy
-- must know about membership, and the membership policy must
-- know about conversations; defining either inline deadlocks.
-- ------------------------------------------------------------

create or replace function public.is_admin()
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare v_found boolean;
begin
  -- plpgsql, not sql: an SQL-language body is analysed at creation
  -- time, and these helpers are defined before the tables exist.
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.is_admin
  ) into v_found;
  return coalesce(v_found, false);
end;
$$;

create or replace function public.is_conversation_member(p_conversation_id uuid)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare v_found boolean;
begin
  select exists (
    select 1 from public.conversation_members m
    where m.conversation_id = p_conversation_id and m.user_id = auth.uid()
  ) or exists (
    select 1 from public.conversations c
    where c.id = p_conversation_id
      and (c.customer_id = auth.uid() or c.provider_id = auth.uid())
  ) into v_found;
  return coalesce(v_found, false);
end;
$$;

revoke all on function public.is_admin() from public;
revoke all on function public.is_conversation_member(uuid) from public;
grant execute on function public.is_admin() to anon, authenticated;
grant execute on function public.is_conversation_member(uuid) to authenticated;

